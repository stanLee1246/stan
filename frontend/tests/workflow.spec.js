import { test, expect } from '@playwright/test'

test('student can explore, save profile versions, view recommendations and use a phone layout', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '从这里，看见更多可能.' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '暂无已核实数据' })).toBeVisible()
  await page.getByRole('button', { name: '查看模拟演示' }).click()
  await expect(page.getByRole('img', { name: '毕业去向人数分布' })).toBeVisible()
  await expect(page.getByText('180', { exact: false }).first()).toBeVisible()
  await page.getByRole('link', { name: '登录 / 注册' }).click()
  await page.getByLabel('用户名', { exact: true }).fill('demo_student')
  await page.getByLabel('密码', { exact: true }).fill('DemoStudent123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出' })).toBeVisible()
  await page.getByRole('link', { name: '完善个人画像' }).click()
  await expect(page.getByRole('button', { name: '保存新版本 →' })).toBeEnabled()
  const previousVersions = await page.locator('.timeline-item').count()
  await page.getByLabel('已掌握技能').fill('Python、SQL')
  await page.getByLabel('偏好城市').fill('长沙、衡阳')
  await page.getByRole('button', { name: '保存新版本 →' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  await page.getByLabel('已掌握技能').fill('Python、SQL、MySQL')
  await page.getByRole('button', { name: '保存新版本 →' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  await expect(page.locator('.timeline-item')).toHaveCount(previousVersions + 2)
  await page.locator('.sidebar').getByRole('link', { name: /发展机会/ }).click()
  await page.getByRole('button', { name: '生成我的推荐 ↗' }).click()
  await expect(page.getByRole('heading', { name: '当前画像的参考机会' })).toBeVisible()
  await expect(page.locator('.recommendation-card').first()).toBeVisible()
  await page.locator('.sidebar').getByRole('link', { name: /学校概况/ }).click()
  await expect(page.getByRole('heading', { name: '高校与专业.' })).toBeVisible()
  await expect(page.getByRole('table', { name: '高校原始数据' }).locator('tbody tr')).toHaveCount(13)
  await expect(page.getByText('用户提供 · 待核验', { exact: true })).toBeVisible()
  const source = page.getByRole('link', { name: /学校官网/ })
  await expect(source).toHaveAttribute('href', 'https://hnjt.edu.cn/')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.locator('.sidebar').getByRole('link', { name: /个人画像/ }).click()
  await expect(page.getByRole('heading', { name: '认识自己，也记录变化.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.locator('.sidebar').getByRole('link', { name: /发展总览/ }).click()
  await expect(page.getByRole('img', { name: '毕业去向人数分布' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../.local/mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '../.local/dashboard.png', fullPage: true })
  expect(errors).toEqual([])
})

test('admin can import a CSV and inspect quality results', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('用户名', { exact: true }).fill('demo_admin')
  await page.getByLabel('密码', { exact: true }).fill('DemoAdmin123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.locator('.sidebar').getByRole('link', { name: /数据工作台/ }).click()
  await page.getByLabel('来源名称').fill('浏览器测试：模拟样本')
  await page.getByLabel('UTF-8 CSV 文件').setInputFiles('../data/demo-outcomes.csv')
  await page.getByRole('button', { name: '校验并导入' }).click()
  await expect(page.getByRole('heading', { name: /本次质量报告/ })).toBeVisible()
  await expect(page.getByText('解析正确率需人工抽样核对，当前未测量。', { exact: false })).toBeVisible()
})
