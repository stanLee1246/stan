import { test, expect } from '@playwright/test'

test('owner compares rule and text methods, inspects evidence and exports frozen reports', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const username = `lexical_${Date.now()}`
  const registered = await page.request.post('/api/auth/register', { data: { username, nickname: '算法对照测试', password: 'TextExperiment123!' } })
  expect(registered.status()).toBe(201)
  await page.goto('/login')
  await page.getByLabel('用户名', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill('TextExperiment123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('button', { name: '退出', exact: true })).toBeVisible()
  await page.getByLabel('演示数据', { exact: true }).check()
  await page.goto('/profile')
  await expect(page.getByRole('button', { name: '保存新版本 →' })).toBeEnabled()
  await page.getByLabel('已掌握技能').fill('Python、SQL、MySQL')
  await page.getByLabel('偏好城市').fill('长沙、衡阳')
  await page.getByLabel('项目与经历说明').fill('使用 Python 清洗招聘数据，SQL 建立数据仓库并进行数据分析。')
  await page.getByRole('button', { name: '保存新版本 →' }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  await page.goto('/experiments')
  await page.getByRole('button', { name: '运行推荐方法对照 →' }).click()
  await expect(page.getByRole('heading', { name: '2 · 本次实验范围' })).toBeVisible()
  const table = page.getByRole('table').first()
  await expect(table).toBeVisible()
  await expect(table).toContainText('词面余弦')
  await expect(page.locator('.experiment-terms .tag').first()).toBeVisible()
  await table.getByText('查看计算依据', { exact: true }).first().click()
  await expect(table.getByText('词片段贡献总和', { exact: false }).first()).toBeVisible()
  const jsonEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出完整结果 JSON ↓' }).click()
  expect((await jsonEvent).suggestedFilename()).toBe('recommendation-comparison-demo-profile-v1.json')
  const mdEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出对照报告 Markdown ↓' }).click()
  expect((await mdEvent).suggestedFilename()).toBe('recommendation-comparison-demo-profile-v1.md')
  await page.screenshot({ path: '../.local/experiments-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: '../.local/experiments-mobile.png', fullPage: true })
  await page.getByLabel('演示数据', { exact: true }).uncheck()
  await expect(page.getByRole('heading', { name: '2 · 本次实验范围' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '运行推荐方法对照 →' })).toBeEnabled()
  await page.getByRole('button', { name: '运行推荐方法对照 →' }).click()
  await expect(page.getByRole('heading', { name: '当前没有符合已知条件的候选' })).toBeVisible()
  expect(errors).toEqual([])
})
